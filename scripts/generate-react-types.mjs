#!/usr/bin/env node
/**
 * Reads packages/core/custom-elements.json and emits packages/core/react.d.ts.
 * The output augments React's JSX.IntrinsicElements with one entry per tagged
 * AetherUI component so React 19+ consumers get full prop and custom-event
 * autocomplete for tags like <ae-checkbox checked onAeCheckboxChange={...}>.
 *
 * Run via `pnpm gen:react-types` from packages/core (or as part of build).
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..');
const manifestPath = resolve(repoRoot, 'packages/core/custom-elements.json');
const outPath = resolve(repoRoot, 'packages/core/react.d.ts');

const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));

const isPublicField = (member) =>
  member.kind === 'field' &&
  !member.static &&
  member.privacy !== 'private' &&
  member.privacy !== 'protected' &&
  !member.name.startsWith('_');

const kebabToPascal = (s) =>
  s.split('-').map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join('');

const eventToHandler = (eventName) => `on${kebabToPascal(eventName)}`;

const components = [];
for (const mod of manifest.modules) {
  for (const decl of mod.declarations ?? []) {
    if (decl.kind !== 'class' || !decl.tagName) continue;
    const props = (decl.members ?? []).filter(isPublicField).map((m) => ({
      name: m.name,
      type: m.type?.text ?? 'unknown',
      description: m.description,
    }));
    const events = (decl.events ?? []).map((e) => ({
      handler: eventToHandler(e.name),
      type: e.type?.text ?? 'CustomEvent',
      description: e.description,
    }));
    components.push({ tagName: decl.tagName, className: decl.name, props, events });
  }
}

components.sort((a, b) => a.tagName.localeCompare(b.tagName));

const banner = `/**
 * AUTO-GENERATED by scripts/generate-react-types.mjs from custom-elements.json.
 * Do not edit by hand. Re-run \`pnpm --filter @aetherui/core gen:react-types\`
 * (or just \`pnpm --filter @aetherui/core build\`) to regenerate.
 *
 * Reference this file from your tsconfig (\`"types": ["@aetherui/core/react"]\`)
 * or include it explicitly. Requires React 19+ for runtime prop/event binding.
 */
`;

const renderEntry = ({ tagName, props, events, className }) => {
  const propLines = props.map((p) => {
    const doc = p.description ? `        /** ${p.description.replace(/\n/g, ' ')} */\n` : '';
    return `${doc}        ${p.name}?: ${p.type};`;
  });
  const eventLines = events.map((e) => {
    const doc = e.description ? `        /** ${e.description.replace(/\n/g, ' ')} */\n` : '';
    return `${doc}        ${e.handler}?: (event: ${e.type}) => void;`;
  });
  const body = [...propLines, ...eventLines].join('\n');
  return `      /** ${className ?? tagName} — see https://github.com/pallavL01/AetherUI for docs. */
      '${tagName}': React.DetailedHTMLProps<
        React.HTMLAttributes<HTMLElement>,
        HTMLElement
      > & {
${body || '        // (no public props)'}
      };`;
};

const body = components.map(renderEntry).join('\n');

const output = `${banner}
import type * as React from 'react';

declare module 'react' {
  namespace JSX {
    interface IntrinsicElements {
${body}
    }
  }
}

export {};
`;

writeFileSync(outPath, output);
console.log(
  `Wrote ${outPath} (${components.length} components, ${components.reduce((n, c) => n + c.props.length, 0)} props, ${components.reduce((n, c) => n + c.events.length, 0)} events).`,
);
