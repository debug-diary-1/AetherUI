#!/usr/bin/env node

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const manifestPath = resolve(root, 'packages/core/custom-elements.json');
const checkOnly = process.argv.includes('--check');
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));

const clean = (value) => (typeof value === 'string' ? value.trim() : '');
const publicProperties = (declaration) =>
  (declaration.members ?? [])
    .filter(
      (member) =>
        member.kind === 'field' &&
        !member.static &&
        member.privacy !== 'private' &&
        member.privacy !== 'protected' &&
        !member.name.startsWith('_') &&
        typeof member.attribute === 'string',
    )
    .map((member) => ({
      name: member.name,
      attribute: member.attribute ?? null,
      type: member.type?.text ?? 'unknown',
      default: member.default ?? null,
      description: clean(member.description),
    }))
    .sort((a, b) => a.name.localeCompare(b.name));

const components = manifest.modules
  .flatMap((module) =>
    (module.declarations ?? [])
      .filter((declaration) => declaration.kind === 'class' && declaration.tagName)
      .map((declaration) => ({
        tagName: declaration.tagName,
        className: declaration.name,
        module: module.path,
        description: clean(declaration.description),
        properties: publicProperties(declaration),
        events: (declaration.events ?? [])
          .map((event) => ({
            name: event.name,
            type: event.type?.text ?? 'CustomEvent<unknown>',
            description: clean(event.description),
          }))
          .sort((a, b) => a.name.localeCompare(b.name)),
        slots: (declaration.slots ?? [])
          .map((slot) => ({ name: slot.name ?? '', description: clean(slot.description) }))
          .sort((a, b) => a.name.localeCompare(b.name)),
        cssParts: (declaration.cssParts ?? [])
          .map((part) => ({ name: part.name, description: clean(part.description) }))
          .sort((a, b) => a.name.localeCompare(b.name)),
        cssProperties: (declaration.cssProperties ?? [])
          .map((property) => ({ name: property.name, description: clean(property.description) }))
          .sort((a, b) => a.name.localeCompare(b.name)),
      })),
  )
  .sort((a, b) => a.tagName.localeCompare(b.tagName));

const catalog = {
  schemaVersion: '1.0.0',
  source: 'packages/core/custom-elements.json',
  components,
};

const agentUiSchema = {
  $schema: 'https://json-schema.org/draft/2020-12/schema',
  $id: 'https://debug-diary-1.github.io/AetherUI/docs/agent-ui.schema.json',
  title: 'AetherUI Agent Document',
  description: 'A constrained, validated document for rendering AetherUI custom elements.',
  type: 'object',
  additionalProperties: false,
  required: ['version', 'root'],
  properties: {
    version: { const: '1' },
    root: { $ref: '#/$defs/node' },
  },
  $defs: {
    jsonValue: {
      anyOf: [
        { type: 'string' },
        { type: 'number' },
        { type: 'boolean' },
        { type: 'null' },
        { type: 'array', items: { $ref: '#/$defs/jsonValue' } },
        { type: 'object', additionalProperties: { $ref: '#/$defs/jsonValue' } },
      ],
    },
    node: {
      type: 'object',
      additionalProperties: false,
      required: ['component'],
      properties: {
        component: { enum: components.map((component) => component.tagName) },
        id: { type: 'string' },
        slot: { type: 'string' },
        props: { type: 'object', additionalProperties: { $ref: '#/$defs/jsonValue' } },
        actions: { type: 'object', additionalProperties: { type: 'string', minLength: 1 } },
        children: {
          type: 'array',
          items: { anyOf: [{ type: 'string' }, { $ref: '#/$defs/node' }] },
        },
      },
    },
  },
};

const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
const compactContracts = components.map(({ tagName, properties, events }) => ({
  tagName,
  properties: properties.map(({ name, attribute, type }) => ({ name, attribute, type })),
  events: events.map(({ name, type }) => ({ name, type })),
}));
const generatedTypeScript = `/* AUTO-GENERATED by scripts/generate-agent-artifacts.mjs. */
import type { AgentUiComponentContract } from './types.js';

export const componentCatalog = ${JSON.stringify(compactContracts, null, 2)} as const satisfies readonly AgentUiComponentContract[];
`;

const renderList = (items, render) =>
  items.length ? items.map(render).join('\n') : '- None documented';
const renderComponent = (component) => `## \`<${component.tagName}>\`

${component.description || `${component.className} custom element.`}

Properties:
${renderList(component.properties, (property) => `- \`${property.name}\` (${property.type}${property.default ? `, default ${property.default}` : ''}): ${property.description || 'No description.'}`)}

Events:
${renderList(component.events, (event) => `- \`${event.name}\` (${event.type}): ${event.description || 'No description.'}`)}

Slots:
${renderList(component.slots, (slot) => `- \`${slot.name || 'default'}\`: ${slot.description || 'No description.'}`)}

CSS parts:
${renderList(component.cssParts, (part) => `- \`${part.name}\`: ${part.description || 'No description.'}`)}
`;

const llms = `# AetherUI

> Headless, accessible custom elements built with Lit. Register elements explicitly, import one token theme, and use the documented properties and custom events.

## Canonical resources

- /component-catalog.json — machine-readable element interfaces
- /agent-ui.schema.json — constrained runtime-generated UI document
- /llms-full.txt — complete property, event, slot, and CSS-part reference
- /getting-started/installation/ — installation and registration
- /getting-started/integrations/react/ — React 19 JSX typing

## Rules

- Import from @aetherui/core or a documented subpath and call the matching define function once.
- Import @aetherui/tokens/light.css or @aetherui/tokens/dark.css once.
- Listen for documented ae-* CustomEvents; read payloads from event.detail.
- Treat accessibility and keyboard behavior as part of each element's interface.
- For model-generated interfaces, emit the JSON schema and validate it with @aetherui/agent before rendering.
`;

const llmsFull = `${llms}\n# Complete component catalog\n\n${components.map(renderComponent).join('\n')}`;

const artifacts = new Map([
  ['packages/core/component-catalog.json', json(catalog)],
  ['packages/docs/public/component-catalog.json', json(catalog)],
  ['packages/agent/component-catalog.json', json(catalog)],
  ['packages/mcp/component-catalog.json', json(catalog)],
  ['packages/docs/public/agent-ui.schema.json', json(agentUiSchema)],
  ['packages/agent/agent-ui.schema.json', json(agentUiSchema)],
  ['packages/mcp/agent-ui.schema.json', json(agentUiSchema)],
  ['packages/agent/src/catalog.generated.ts', generatedTypeScript],
  ['packages/docs/public/llms.txt', llms],
  ['packages/docs/public/llms-full.txt', llmsFull],
]);

let stale = false;
for (const [path, content] of artifacts) {
  const absolutePath = resolve(root, path);
  if (checkOnly) {
    let current = '';
    try {
      current = readFileSync(absolutePath, 'utf8');
    } catch {
      // Missing is stale.
    }
    if (current !== content) {
      console.error(`Stale generated artifact: ${relative(root, absolutePath)}`);
      stale = true;
    }
  } else {
    writeFileSync(absolutePath, content);
    console.log(`Wrote ${relative(root, absolutePath)}`);
  }
}

if (stale) {
  console.error('Run pnpm generate:agent-artifacts.');
  process.exit(1);
}
