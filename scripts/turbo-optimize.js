#!/usr/bin/env node

/**
 * This script optimizes Turborepo's cache performance and build speed.
 * It performs several actions to ensure optimal Turborepo configuration:
 * 
 * 1. Cleans up any stale cache entries
 * 2. Prunes unnecessary node_modules for faster builds
 * 3. Sets up parallel execution based on available CPUs
 * 4. Configures environment for optimal build performance
 * 
 * Usage:
 *   node scripts/turbo-optimize.js [options]
 * 
 * Options:
 *   --ci           Configure for CI/CD environment
 *   --remote       Set up and use remote caching
 *   --aggressive   Perform more aggressive optimizations
 */

const { execSync } = require('child_process');
const os = require('os');
const fs = require('fs');
const path = require('path');

// Parse arguments
const args = process.argv.slice(2);
const isCI = args.includes('--ci');
const useRemote = args.includes('--remote');
const aggressive = args.includes('--aggressive');

// Get optimal concurrency level
const cpuCount = os.cpus().length;
const concurrency = isCI ? Math.max(cpuCount - 1, 2) : Math.max(cpuCount - 2, 2);

console.log('\n🚀 Turborepo Optimization\n');
console.log(`CPU cores detected: ${cpuCount}`);
console.log(`Setting optimal concurrency: ${concurrency}`);

// Determine available memory
const totalMemory = Math.floor(os.totalmem() / (1024 * 1024 * 1024)); // GB
console.log(`Available memory: ${totalMemory}GB`);

try {
  // Step 1: Clean turbo cache
  console.log('\n🧹 Cleaning Turborepo cache...');
  execSync('pnpm run turbo:cache:clean', { stdio: 'inherit' });

  // Step 2: Optimize Node.js settings for better build performance
  console.log('\n⚙️ Setting optimal Node.js build environment...');
  
  // Create .env.local file with optimized settings
  const envPath = path.join(__dirname, '..', '.env.local');
  const envContent = `# Turborepo optimized settings
# Generated by turbo-optimize.js
NODE_OPTIONS=--max-old-space-size=${totalMemory >= 16 ? 8192 : totalMemory >= 8 ? 4096 : 2048}
TURBO_TELEMETRY_DISABLED=1
${isCI ? 'CI=true' : ''}
`;

  fs.writeFileSync(envPath, envContent);
  console.log(`✅ Environment settings saved to ${envPath}`);

  // Step 3: Set up remote caching if requested
  if (useRemote) {
    console.log('\n☁️ Setting up remote caching...');
    if (isCI) {
      execSync('pnpm run turbo:remote-cache:ci', { stdio: 'inherit' });
    } else {
      execSync('pnpm run turbo:remote-cache:setup', { stdio: 'inherit' });
    }
  }

  // Step 4: Update .turborc.json with optimized settings (if aggressive)
  if (aggressive) {
    console.log('\n⚡ Applying aggressive optimizations...');
    
    const turboRcPath = path.join(__dirname, '..', '.turborc.json');
    const turboRcContent = {
      "concurrency": concurrency,
      "experimentalSpaces": true,
      "experimentalRebuild": true,
      "apiUrl": "https://vercel.com/api/turborepo"
    };
    
    fs.writeFileSync(turboRcPath, JSON.stringify(turboRcContent, null, 2));
    console.log(`✅ Advanced Turborepo settings saved to ${turboRcPath}`);
  }

  // Step 5: Run a dry build to validate and warm up cache
  console.log('\n🔍 Validating Turborepo configuration...');
  execSync(`pnpm exec turbo run build --dry-run --concurrency=${concurrency}`, {
    stdio: 'inherit'
  });

  console.log('\n✅ Turborepo optimization complete!');
  console.log('\nRecommended build commands:');
  console.log(`- Regular build:   pnpm run build`);
  console.log(`- Fast build:      pnpm run build:fast`);
  console.log(`- CI build:        pnpm run ci`);
  if (useRemote) {
    console.log(`- Remote cache:    pnpm run turbo:remote-cache:on`);
  }

} catch (error) {
  console.error('\n❌ Error optimizing Turborepo:', error.message);
  process.exit(1);
}